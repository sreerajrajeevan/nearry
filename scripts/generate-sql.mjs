import { readFile, readdir, writeFile } from 'node:fs/promises';
const folder = new URL('../supabase/migrations/', import.meta.url);
const files = (await readdir(folder)).filter(name => name.endsWith('.sql')).sort();
let sql = `-- GENERATED by npm run sql:generate. FRESH DATABASES ONLY.\n-- Existing projects: apply only unapplied numbered migrations.\nbegin;\ndo $$ begin if to_regclass('public.profiles') is not null then\n raise exception 'Existing database: use numbered forward migrations instead of run-all.sql';\nend if; end; $$;\n`;
for (const file of files) sql += `\n-- ${file}\n` + (await readFile(new URL(file, folder), 'utf8')).replace(/^(begin;|commit;)\s*$/gm, '') + '\n';
sql += '\ncommit;\n';
const target = new URL('../supabase/run-all.sql', import.meta.url);
if(process.argv.includes('--check')) { if(await readFile(target,'utf8')!==sql) throw new Error('Run npm run sql:generate and commit the result.'); }
else await writeFile(target, sql);
